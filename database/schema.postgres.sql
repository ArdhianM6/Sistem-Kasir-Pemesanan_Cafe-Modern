-- Jalankan file ini pada database PostgreSQL kosong sebelum menjalankan seed.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid UUID NOT NULL UNIQUE,
  username VARCHAR(60) NOT NULL UNIQUE,
  email VARCHAR(190) NOT NULL UNIQUE,
  full_name VARCHAR(120) NOT NULL,
  role VARCHAR(16) NOT NULL DEFAULT 'cashier' CHECK (role IN ('admin','manager','cashier','waiter')),
  status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE, slug VARCHAR(100) NOT NULL UNIQUE,
  status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK(status IN ('active','inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  sku VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
  selling_price INTEGER NOT NULL CHECK(selling_price >= 0), cost_price INTEGER NOT NULL DEFAULT 0 CHECK(cost_price >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0), unit VARCHAR(24) NOT NULL DEFAULT 'porsi',
  status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK(status IN ('active','inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_products_status_stock ON products(status,stock);
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, invoice_number VARCHAR(48) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  order_type VARCHAR(12) NOT NULL CHECK(order_type IN ('dine_in','takeaway')), table_number VARCHAR(12), customer_name VARCHAR(120),
  subtotal INTEGER NOT NULL, discount INTEGER NOT NULL DEFAULT 0, tax_amount INTEGER NOT NULL DEFAULT 0, service_amount INTEGER NOT NULL DEFAULT 0, grand_total INTEGER NOT NULL,
  payment_method VARCHAR(12) NOT NULL CHECK(payment_method IN ('cash','qris','transfer','debit')),
  amount_paid INTEGER NOT NULL, change_amount INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(12) NOT NULL DEFAULT 'processing' CHECK(status IN ('processing','completed','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_orders_created_status ON orders(created_at,status);
CREATE TABLE IF NOT EXISTS order_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON UPDATE CASCADE ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON UPDATE CASCADE ON DELETE SET NULL,
  product_name VARCHAR(120) NOT NULL, unit_label VARCHAR(24) NOT NULL DEFAULT 'item',
  unit_price INTEGER NOT NULL, quantity SMALLINT NOT NULL CHECK(quantity > 0), line_total INTEGER NOT NULL, notes VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_order_details_product ON order_details(product_id);
